package main

import "net/http"

// mgRoutes registers the management API. Forms are posted as FormData and answer a FormState;
// writes are journaled by the handlers (mgLog) with homelab-management's wording.
func (s *Server) mgRoutes(mux *http.ServeMux) {
	a := s.requireAuth
	h := func(pattern string, fn http.HandlerFunc) { mux.HandleFunc(pattern, a(fn)) }

	h("GET /api/settings", s.handleMgSettings)
	h("PUT /api/settings", s.handlePutSettings)
	h("GET /api/mg/stats", s.mgStats)
	h("GET /api/mg/export", s.mgExport)
	h("POST /api/mg/import", s.mgImport)

	// Inventory
	h("GET /api/mg/assets", s.mgListAssets)
	h("GET /api/mg/assets/options", s.mgAssetOptions)
	h("GET /api/mg/assets/meta", s.mgInventoryMeta)
	h("POST /api/mg/assets", s.mgSaveAsset)
	h("POST /api/mg/assets/bulk", s.mgBulkAssets)
	h("GET /api/mg/assets/{id}", s.mgAsset)
	h("POST /api/mg/assets/{id}", s.mgSaveAsset)
	h("DELETE /api/mg/assets/{id}", s.mgDeleteAsset)
	h("POST /api/mg/assets/{id}/duplicate", s.mgDuplicateAsset)
	h("POST /api/mg/assets/{id}/status", s.mgSetAssetStatus)
	h("GET /api/mg/assets/{id}/monitoring", s.mgAssetMonitoring)
	h("POST /api/mg/assets/{id}/decommission", s.mgDecomStart)
	h("POST /api/mg/assets/{id}/decommission/step", s.mgDecomStep)
	h("POST /api/mg/assets/{id}/decommission/cancel", s.mgDecomCancel)
	h("POST /api/mg/assets/{id}/decommission/finish", s.mgDecomFinish)
	h("POST /api/mg/sync", s.mgSyncNow)
	h("GET /api/mg/agents", s.mgAgents)
	h("POST /api/mg/agents/update", s.mgUpdateAgents)

	// Hardware stock
	h("GET /api/mg/hardware", s.mgListHardware)
	h("POST /api/mg/hardware", s.mgSaveHardware)
	h("POST /api/mg/hardware/{id}", s.mgSaveHardware)
	h("DELETE /api/mg/hardware/{id}", s.mgDeleteHardware)
	h("POST /api/mg/hardware/{id}/install", s.mgInstallHardware)
	h("POST /api/mg/hardware/{id}/duplicate", s.mgDuplicateHardware)

	// Network
	h("GET /api/mg/network", s.mgNetwork)
	h("POST /api/mg/vlans", s.mgSaveVlan)
	h("POST /api/mg/vlans/{id}", s.mgSaveVlan)
	h("DELETE /api/mg/vlans/{id}", s.mgDelete("vlans", "vlan", "vlan_id", "Suppression du VLAN %s"))
	h("POST /api/mg/subnets", s.mgSaveSubnet)
	h("POST /api/mg/subnets/{id}", s.mgSaveSubnet)
	h("DELETE /api/mg/subnets/{id}", s.mgDelete("subnets", "subnet", "cidr", "Suppression du sous-réseau %s"))
	h("GET /api/mg/subnets/{id}/next-free", s.mgNextFreeIP)
	h("GET /api/mg/ips", s.mgListIPs)
	h("POST /api/mg/ips", s.mgSaveIP)
	h("POST /api/mg/ips/{id}", s.mgSaveIP)
	h("DELETE /api/mg/ips/{id}", s.mgDelete("ip_addresses", "ip", "address", "Libération de %s"))
	h("POST /api/mg/ips/{id}/primary", s.mgSetPrimaryIP)
	h("POST /api/mg/vpn", s.mgSaveVpn)
	h("POST /api/mg/vpn/{id}", s.mgSaveVpn)
	h("DELETE /api/mg/vpn/{id}", s.mgDelete("vpn_tunnels", "vpn", "name", "Tunnel VPN « %s » supprimé"))
	h("POST /api/mg/firewall", s.mgSaveRule)
	h("POST /api/mg/firewall/{id}", s.mgSaveRule)
	h("DELETE /api/mg/firewall/{id}", s.mgDelete("firewall_rules", "firewall", "name", "Règle de pare-feu « %s » supprimée"))
	h("POST /api/mg/firewall/{id}/toggle", s.mgToggleRule)
	h("POST /api/mg/firewall/{id}/move", s.mgMove("firewall_rules"))
	h("PUT /api/mg/firewall-policy", s.mgSetPolicy)
	h("POST /api/mg/domains", s.mgSaveDomain)
	h("POST /api/mg/domains/{id}", s.mgSaveDomain)
	h("DELETE /api/mg/domains/{id}", s.mgDelete("domains", "domain", "fqdn", "Domaine « %s » supprimé"))

	// Deployments and tasks
	h("GET /api/mg/work", s.mgWorkOptions)
	h("GET /api/mg/deployments", s.mgListDeployments)
	h("POST /api/mg/deployments", s.mgSaveDeployment)
	h("GET /api/mg/deployments/{id}", s.mgDeployment)
	h("POST /api/mg/deployments/{id}", s.mgSaveDeployment)
	h("DELETE /api/mg/deployments/{id}", s.mgDelete("deployments", "deployment", "title", "Suppression du déploiement « %s »"))
	h("POST /api/mg/deployments/{id}/status", s.mgSetDeploymentStatus)
	h("POST /api/mg/deployments/{id}/steps", s.mgAddStep)
	h("POST /api/mg/deployments/{id}/promote", s.mgPromoteDeployment)
	h("POST /api/mg/steps/{id}/toggle", s.mgToggleStep)
	h("DELETE /api/mg/steps/{id}", s.mgDeleteStep)
	h("GET /api/mg/tasks", s.mgListTasks)
	h("POST /api/mg/tasks", s.mgSaveTask)
	h("POST /api/mg/tasks/clear-done", s.mgClearDoneTasks)
	h("POST /api/mg/tasks/{id}", s.mgSaveTask)
	h("DELETE /api/mg/tasks/{id}", s.mgDelete("tasks", "task", "title", "Suppression de la tâche « %s »"))
	h("POST /api/mg/tasks/{id}/move", s.mgMoveTask)

	// Start page and map
	h("GET /api/mg/shortcuts", s.mgShortcuts)
	h("POST /api/mg/shortcuts", s.mgSaveShortcut)
	h("POST /api/mg/shortcuts/reorder", s.mgReorderShortcuts)
	h("POST /api/mg/shortcuts/probe", s.mgProbeShortcuts)
	h("POST /api/mg/shortcuts/{id}", s.mgSaveShortcut)
	h("DELETE /api/mg/shortcuts/{id}", s.mgDelete("shortcuts", "shortcut", "name", "Raccourci « %s » supprimé"))
	h("POST /api/mg/groups", s.mgSaveGroup)
	h("POST /api/mg/groups/{id}", s.mgSaveGroup)
	h("DELETE /api/mg/groups/{id}", s.mgDelete("shortcut_groups", "shortcut", "name", "Groupe « %s » supprimé"))
	h("POST /api/mg/groups/{id}/move", s.mgMove("shortcut_groups"))
	h("GET /api/mg/icons/search", s.mgSearchIcons)
	h("POST /api/mg/icons", s.mgUploadIcon)
	h("DELETE /api/mg/icons/{id}", s.mgDeleteIcon)
	mux.HandleFunc("GET /api/uploads/{file}", s.mgServeUpload) // <img> requests carry the cookie, names are random
	h("GET /api/mg/map", s.mgMap)
	h("PUT /api/mg/map/positions", s.mgSavePositions)
	h("DELETE /api/mg/map/positions", s.mgResetPositions)
	h("POST /api/mg/map/links", s.mgCreateLink)
	h("DELETE /api/mg/map/links/{id}", s.mgDeleteLink)

	// Integrations
	h("GET /api/mg/integrations", s.mgListIntegrations)
	h("POST /api/mg/integrations", s.mgSaveIntegration)
	h("POST /api/mg/integrations/test", s.mgTestIntegration)
	h("POST /api/mg/integrations/{id}", s.mgSaveIntegration)
	h("DELETE /api/mg/integrations/{id}", s.mgDelete("integrations", "integration", "name", "Intégration « %s » supprimée"))
	h("GET /api/mg/ssh-keys", s.mgListSSHKeys)
	h("POST /api/mg/ssh-keys", s.mgSaveSSHKey)
	h("DELETE /api/mg/ssh-keys/{id}", s.mgDelete("ssh_keys", "system", "name", "Clé SSH « %s » supprimée"))
	h("GET /api/mg/monitoring", s.mgMonitoring)
	h("GET /api/mg/monitoring/bandwidth/live", s.mgLiveBandwidth)
	h("GET /api/mg/energy", s.mgEnergy)
	h("GET /api/mg/webmin", s.mgWebmin)

	// Proxmox
	h("GET /api/mg/proxmox", s.mgProxmox)
	h("POST /api/mg/proxmox/migrate", s.mgPveMigrate)
	h("GET /api/mg/proxmox/{id}", s.mgProxmoxOne)
	h("GET /api/mg/proxmox/{id}/targets", s.mgPveTargets)
	h("GET /api/mg/proxmox/{id}/node/{node}/{what}", s.mgPveNode)
	h("POST /api/mg/proxmox/{id}/node/{node}/service/{service}/{action}", s.mgPveService)
	h("POST /api/mg/proxmox/{id}/node/{node}/apt-refresh", s.mgPveAptRefresh)
	h("POST /api/mg/proxmox/{id}/node/{node}/power", s.mgPvePower)
	h("GET /api/mg/proxmox/{id}/guest/{node}/{type}/{vmid}/{what}", s.mgPveGuest)
	h("POST /api/mg/proxmox/{id}/guest/{node}/{type}/{vmid}/action", s.mgPveGuestAction)
	h("POST /api/mg/proxmox/{id}/guest/{node}/{type}/{vmid}/config", s.mgPveGuestConfig)
	h("POST /api/mg/proxmox/{id}/guest/{node}/{type}/{vmid}/snapshot", s.mgPveSnapshot)
	h("POST /api/mg/proxmox/{id}/guest/{node}/{type}/{vmid}/snapshot/{snap}/{command}", s.mgPveSnapshotCommand)
	h("POST /api/mg/proxmox/{id}/guest/{node}/{type}/{vmid}/backup", s.mgPveBackup)
	h("POST /api/mg/proxmox/{id}/guest/{node}/{type}/{vmid}/vnc", s.mgVncSession)
	mux.HandleFunc("GET /api/mg/vnc", s.mgVncRelay) // checks the session itself (WebSocket upgrade)
}
